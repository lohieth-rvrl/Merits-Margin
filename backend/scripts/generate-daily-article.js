#!/usr/bin/env node
/**
 * Daily article automation.
 *
 * What this does, in order:
 *   1. Picks the next topic from scripts/topics.js (cycling through the list,
 *      remembering position in scripts/state.json).
 *   2. Calls the free Gemini API (Google AI Studio) to write a full article
 *      for that topic.
 *   3. Finds a real cover photo and one in-body photo via the Pexels API
 *      (free, own key, real stock photography -- no AI generation involved).
 *      Without a key, these are simply skipped and the site's own generated
 *      category illustration shows instead.
 *   4. Optionally finds one related YouTube video via the YouTube Data API
 *      (free, but needs its own separate API key -- skipped automatically
 *      if you haven't set one up).
 *   5. Appends a "Sources & further reading" section linking to a fixed,
 *      hand-picked list of real, stable authoritative sites (never
 *      model-generated, so it can never cite a fabricated or dead link).
 *   6. Saves it as a DRAFT through the backend's normal API -- it never
 *      appears on the public site until you open the admin dashboard and
 *      publish it yourself.
 *
 * Run manually with:   node scripts/generate-daily-article.js
 * Schedule it with cron/Task Scheduler -- see README.md for exact steps.
 *
 * Required environment variables (put these in backend/.env):
 *   GEMINI_API_KEY      Free key from https://aistudio.google.com/app/apikey
 *                        -- no credit card required.
 *   API_URL             Your backend's API base, e.g. http://localhost:5000/api
 *   SEED_ADMIN_EMAIL    Same admin login used by seed.js
 *   SEED_ADMIN_PASSWORD Same admin login used by seed.js
 *   GEMINI_MODEL        Optional. Defaults to a current free-tier model.
 *   PEXELS_API_KEY      Optional. Free key from https://www.pexels.com/api/
 *                        -- enables real cover/in-body photos. Without it,
 *                        the site's generated illustration shows instead.
 *   YOUTUBE_API_KEY     Optional. Free key from Google Cloud Console --
 *                        see README for setup. Without it, the "Related
 *                        video" section is simply skipped.
 */

require("dotenv").config();
const fs = require("fs");
const path = require("path");
const nodemailer = require("nodemailer");
const sources = require("./sources"); // kept only as a fallback if dynamic source generation fails

const STATE_PATH = path.join(__dirname, "state.json");
const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const PEXELS_API_KEY = process.env.PEXELS_API_KEY || "";
const YOUTUBE_API_KEY = process.env.YOUTUBE_API_KEY || "";
const API_URL = process.env.API_URL || "http://localhost:5000/api";
const ADMIN_EMAIL = process.env.SEED_ADMIN_EMAIL;
const ADMIN_PASSWORD = process.env.SEED_ADMIN_PASSWORD;
const MODEL = process.env.GEMINI_MODEL || "gemini-2.5-flash";
const SLACK_WEBHOOK_URL = process.env.SLACK_WEBHOOK_URL || "";
const EMAIL_TO = process.env.EMAIL_TO || "";
const EMAIL_FROM = process.env.EMAIL_FROM || "";
const EMAIL_APP_PASSWORD = process.env.EMAIL_APP_PASSWORD || "";

function fail(message) {
  console.error(`\n❌ ${message}\n`);
  process.exit(1);
}

if (!GEMINI_API_KEY) fail("GEMINI_API_KEY is not set in backend/.env — get a free one at https://aistudio.google.com/app/apikey");
if (!ADMIN_EMAIL || !ADMIN_PASSWORD) fail("SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD are not set in backend/.env");

// ---------------------------------------------------------------- state
const CATEGORY_CYCLE = ["finance", "career", "news"];

function loadState() {
  try {
    return JSON.parse(fs.readFileSync(STATE_PATH, "utf8"));
  } catch {
    return { lastCategoryIndex: -1, recentTopics: [] };
  }
}
function saveState(state) {
  fs.writeFileSync(STATE_PATH, JSON.stringify(state, null, 2));
}

// The category still rotates in a fixed, predictable cycle so the site
// stays balanced across sections. Only the specific topic within that
// category is freshly generated by Gemini on every run (see
// generateTopic() below) -- there's no more static topic list.
function getNextCategory(state) {
  return CATEGORY_CYCLE[(state.lastCategoryIndex + 1) % CATEGORY_CYCLE.length];
}

async function generateTopic(category, recentTopics) {
  const avoidBlock = recentTopics.length
    ? `Avoid these recently covered topics:\n${recentTopics.map((t) => `- ${t}`).join("\n")}\n\n`
    : "";

  const prompt = `Suggest ONE specific, practical, high-interest article topic for the "${category}" section of a plain-spoken personal finance and career website (real, actionable advice -- no vague generalities, no jargon).

${avoidBlock}Respond with ONLY the topic itself as a single line -- no numbering, no quotation marks, no preamble, no extra commentary.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json", "x-goog-api-key": GEMINI_API_KEY },
    body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }] }),
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini topic-generation error (${response.status}): ${errText}`);
  }

  const data = await response.json();
  const candidate = data.candidates?.[0];
  const text = candidate?.content?.parts?.map((p) => p.text).join("").trim();
  if (!text) throw new Error("Gemini returned no topic text.");

  // Strip any surrounding quotes the model might add despite instructions
  return text.replace(/^["']+|["']+$/g, "").trim();
}

// ---------------------------------------------------------------- helpers
function slugify(text) {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-");
}

function extractToc(body) {
  const matches = [...body.matchAll(/^##\s+(.+)$/gm)];
  return matches.map((m) => m[1].trim());
}

function estimateReadTime(body) {
  const words = body.trim().split(/\s+/).length;
  const minutes = Math.max(1, Math.round(words / 200));
  return `${minutes} min read`;
}

function parseModelReply(text) {
  const titleMatch = text.match(/^TITLE:\s*(.+)$/m);
  const dekMatch = text.match(/^DEK:\s*(.+)$/m);
  const bodyMarker = text.indexOf("===BODY===");

  if (!titleMatch || !dekMatch || bodyMarker === -1) {
    throw new Error("Model reply didn't match the expected TITLE/DEK/===BODY=== format.");
  }

  const title = titleMatch[1].trim();
  const dek = dekMatch[1].trim();
  const body = text.slice(bodyMarker + "===BODY===".length).trim();

  if (!title || !dek || !body) {
    throw new Error("Model reply was missing a title, dek, or body.");
  }

  return { title, dek, body };
}

// ---------------------------------------------------------------- images (Pexels API, free, own key)
// Real stock photography, not AI-generated. Returns null if no key is set
// or nothing matches -- callers fall back to the site's own generated
// category illustration in that case.
async function searchPexelsPhoto(query) {
  if (!PEXELS_API_KEY) return null;
  try {
    const url = `https://api.pexels.com/v1/search?query=${encodeURIComponent(query)}&per_page=1&orientation=landscape`;
    const res = await fetch(url, { headers: { Authorization: PEXELS_API_KEY } });
    if (!res.ok) {
      console.log(`   (Pexels search failed for "${query}" — status ${res.status})`);
      return null;
    }
    const data = await res.json();
    const photo = data.photos?.[0];
    if (!photo) return null;
    // "large" is a good balance of quality vs. file size for both cover
    // and in-body use; Pexels serves these from a stable CDN URL.
    return { url: photo.src.large, alt: photo.alt || query, photographer: photo.photographer };
  } catch (err) {
    console.log(`   (Pexels search error for "${query}": ${err.message})`);
    return null;
  }
}

// Places one in-body image right after the first "## heading" line, using
// that heading's own text as the search query so it's actually relevant.
async function insertInlineImage(body) {
  const match = body.match(/^##\s+(.+)$/m);
  if (!match) return body;
  const headingText = match[1].trim();
  const photo = await searchPexelsPhoto(headingText);
  if (!photo) return body;
  const insertAt = match.index + match[0].length;
  const imageMd = `\n\n![${photo.alt}](${photo.url})\n*Photo by ${photo.photographer} on Pexels*\n`;
  return body.slice(0, insertAt) + imageMd + body.slice(insertAt);
}

// ---------------------------------------------------------------- related video (YouTube Data API, free, own key)
async function findRelatedVideo(topic) {
  if (!YOUTUBE_API_KEY) return null;
  try {
    const url = `https://www.googleapis.com/youtube/v3/search?part=snippet&type=video&maxResults=1&q=${encodeURIComponent(topic)}&key=${YOUTUBE_API_KEY}`;
    const res = await fetch(url);
    if (!res.ok) {
      console.log(`   (Skipping video — YouTube API returned ${res.status})`);
      return null;
    }
    const data = await res.json();
    const item = data.items?.[0];
    if (!item?.id?.videoId) return null;
    return { videoId: item.id.videoId, title: item.snippet.title };
  } catch (err) {
    console.log(`   (Skipping video — ${err.message})`);
    return null;
  }
}

// ---------------------------------------------------------------- Gemini call
async function generateArticle(topicEntry) {
  const prompt = `Write an article for a plain-spoken, no-jargon personal finance and career website.

Topic: "${topicEntry.topic}"
Category: ${topicEntry.category}

Requirements:
- Practical and specific -- real numbers, real scripts, real steps where relevant. No vague encouragement.
- 900 to 1400 words in the body.
- Use Markdown. Structure the body into 4 to 6 sections, each starting with "## " followed by a short, specific heading (not "Introduction" or "Conclusion").
- Use **bold** for key terms and at least one bulleted list where it genuinely helps.
- Do not invent fake statistics, studies, or quotes. General, well-established knowledge is fine; specific numbers that could be wrong (current interest rates, current prices) should be described qualitatively instead ("rates have been rising" rather than a specific invented percentage).
- Write a one-sentence "dek" (subtitle/summary) capturing the practical hook of the piece.
- Write a clear, specific title (not clickbait, not generic).

Respond in EXACTLY this format and nothing else -- no preamble, no closing remarks, no markdown code fences around the whole thing:

TITLE: <the title, one line>
DEK: <the one-sentence dek, one line>
===BODY===
<the full markdown body, starting directly with the first ## heading>`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;
  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "x-goog-api-key": GEMINI_API_KEY,
    },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
    }),
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini API error (${response.status}): ${errText}`);
  }

  const data = await response.json();
  const candidate = data.candidates?.[0];
  const text = candidate?.content?.parts?.map((p) => p.text).join("");

  if (!text) {
    const reason = candidate?.finishReason ? ` (finishReason: ${candidate.finishReason})` : "";
    throw new Error(`No text content in Gemini response${reason}.`);
  }

  return parseModelReply(text);
}

// Dynamic sources: you explicitly chose this over the safer fixed-list
// approach, understanding the risk that an AI model can invent a URL that
// looks plausible but doesn't actually exist or is dead. The prompt below
// pushes toward well-known homepages rather than specific article links
// (a homepage can't "go dead" the way a specific article URL can), but this
// does NOT eliminate the hallucination risk -- it's mitigation, not a fix.
// If this call fails or returns nothing usable, we fall back to the
// original hand-picked list in sources.js so the section is never empty.
async function generateSources(topic, category) {
  const prompt = `Suggest 2 to 3 real, well-known, authoritative websites relevant as "further reading" for an article on this topic: "${topic}" (category: ${category}).

Only suggest organizations you are highly confident actually exist -- major government agencies, well-established publications, well-known nonprofits or institutions. Link to each organization's general homepage rather than a specific article, since you cannot verify a specific article URL is real or still online.

Respond in EXACTLY this format, one source per line, nothing else -- no numbering, no preamble, no commentary:

Name | https://example.com`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent`;
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json", "x-goog-api-key": GEMINI_API_KEY },
    body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }] }),
  });

  if (!response.ok) throw new Error(`Gemini source-generation error (${response.status})`);

  const data = await response.json();
  const candidate = data.candidates?.[0];
  const text = candidate?.content?.parts?.map((p) => p.text).join("").trim();
  if (!text) throw new Error("Gemini returned no source text.");

  const parsed = text
    .split("\n")
    .map((line) => line.split("|").map((s) => s.trim()))
    .filter(([name, link]) => name && link && /^https?:\/\//.test(link))
    .map(([name, link]) => ({ name, url: link }));

  if (parsed.length === 0) throw new Error("Couldn't parse any sources from Gemini's reply.");
  return parsed;
}

// ---------------------------------------------------------------- backend calls
async function login() {
  const res = await fetch(`${API_URL}/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email: ADMIN_EMAIL, password: ADMIN_PASSWORD }),
  });
  if (!res.ok) throw new Error(`Login failed (${res.status}): ${await res.text()}`);
  const data = await res.json();
  return data.token;
}

async function getRelatedSlugs(category) {
  try {
    const res = await fetch(`${API_URL}/articles?category=${category}`);
    if (!res.ok) return [];
    const articles = await res.json();
    return articles.slice(0, 2).map((a) => a.slug);
  } catch {
    return [];
  }
}

// ---------------------------------------------------------------- notifications (optional)
async function sendNotification(article) {
  const reviewUrl = `${API_URL.replace(/\/api\/?$/, "")}/admin/articles`;
  const message = `📝 New draft ready: "${article.title}" (${article.category})\nReview and publish: ${reviewUrl}`;

  if (SLACK_WEBHOOK_URL) {
    try {
      await fetch(SLACK_WEBHOOK_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text: message }),
      });
      console.log("   Slack notification sent.");
    } catch (err) {
      console.log(`   (Slack notification failed: ${err.message})`);
    }
  }

  if (EMAIL_TO && EMAIL_FROM && EMAIL_APP_PASSWORD) {
    try {
      const transporter = nodemailer.createTransport({
        service: "gmail",
        auth: { user: EMAIL_FROM, pass: EMAIL_APP_PASSWORD },
      });
      await transporter.sendMail({
        from: EMAIL_FROM,
        to: EMAIL_TO,
        subject: `New draft: ${article.title}`,
        text: message,
      });
      console.log("   Email notification sent.");
    } catch (err) {
      console.log(`   (Email notification failed: ${err.message})`);
    }
  }

  if (!SLACK_WEBHOOK_URL && !EMAIL_TO) {
    console.log("   (No SLACK_WEBHOOK_URL or email vars set — skipping notification. See README.)");
  }
}

async function createDraft(token, payload) {
  const res = await fetch(`${API_URL}/articles`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` },
    body: JSON.stringify(payload),
  });
  if (!res.ok) throw new Error(`Create article failed (${res.status}): ${await res.text()}`);
  return res.json();
}

// ---------------------------------------------------------------- main
async function main() {
  const state = loadState();
  const category = getNextCategory(state);
  console.log(`🎯 Category for today: ${category}`);

  console.log("💡 Asking Gemini for a fresh topic...");
  const topic = await generateTopic(category, state.recentTopics || []);
  const topicEntry = { topic, category };
  console.log(`📝 Topic: "${topic}"`);

  // Advance the category cycle and remember this topic so tomorrow's
  // "avoid these" list stays useful (capped at the last 20 topics).
  saveState({
    lastCategoryIndex: CATEGORY_CYCLE.indexOf(category),
    recentTopics: [...(state.recentTopics || []), topic].slice(-20),
  });

  console.log("🤖 Asking Gemini to write the article...");
  const generated = await generateArticle(topicEntry);

  // Extract the TOC from the model's own headings before we add our own
  // extra sections below, so it never mismatches.
  const toc = extractToc(generated.body);

  console.log("🖼️  Finding a cover photo (Pexels)...");
  let coverImage = "";
  if (PEXELS_API_KEY) {
    const coverPhoto = await searchPexelsPhoto(topicEntry.topic);
    if (coverPhoto) {
      coverImage = coverPhoto.url;
      console.log(`   Found a photo by ${coverPhoto.photographer}.`);
    } else {
      console.log("   No matching photo found — using the site's generated illustration instead.");
    }
  } else {
    console.log("   (No PEXELS_API_KEY set — using the site's generated illustration instead. See README.)");
  }
  let body = await insertInlineImage(generated.body);

  console.log("🎬 Looking for a related video...");
  const video = await findRelatedVideo(topicEntry.topic);
  if (video) {
    body += `\n\n## Related video\n\n<div class="lr-embed-wrapper"><iframe src="https://www.youtube.com/embed/${video.videoId}" allowfullscreen title="${video.title.replace(/"/g, "'")}"></iframe></div>\n`;
    toc.push("Related video");
    console.log(`   Found: "${video.title}"`);
  } else if (!YOUTUBE_API_KEY) {
    console.log("   (No YOUTUBE_API_KEY set — skipping. See README to add one, it's free.)");
  }

  console.log("📚 Asking Gemini to suggest further-reading sources...");
  let sourceList = [];
  try {
    sourceList = await generateSources(topicEntry.topic, topicEntry.category);
    console.log(`   Got ${sourceList.length} source(s) from Gemini.`);
  } catch (err) {
    console.log(`   (Dynamic sources failed — ${err.message}. Falling back to the curated list.)`);
    sourceList = sources[topicEntry.category] || [];
  }
  if (sourceList.length > 0) {
    body += `\n\n## Sources & further reading\n\n${sourceList.map((s) => `- [${s.name}](${s.url})`).join("\n")}\n`;
    toc.push("Sources & further reading");
  }

  const readTime = estimateReadTime(body);
  const dateSuffix = new Date().toISOString().slice(0, 10).replace(/-/g, "");
  const slug = `${slugify(generated.title)}-${dateSuffix}`;

  console.log("🔗 Finding related articles in the same category...");
  const related = await getRelatedSlugs(topicEntry.category);

  console.log("🔑 Logging in as admin...");
  const token = await login();

  console.log("💾 Saving as a draft...");
  const payload = {
    title: generated.title,
    slug,
    category: topicEntry.category,
    dek: generated.dek,
    readTime,
    date: new Date().toISOString().slice(0, 10),
    toc,
    related,
    body,
    coverImage,
    status: "draft",
  };

  const created = await createDraft(token, payload);
  console.log(`\n✅ Draft created: "${created.title}"`);
  console.log(`   Review and publish it from Admin → Articles.\n`);

  console.log("🔔 Sending notification (if configured)...");
  await sendNotification(created);
}

main().catch((err) => {
  console.error("\n❌ Automation run failed:", err.message);
  process.exit(1);
});
